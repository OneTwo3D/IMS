/**
 * AN INSTALL.SH RE-RUN MUST NOT SILENTLY DISCARD WHAT THE OPERATOR ALREADY HAS IN .env (D4 re-run).
 *
 * The file was rewritten from a template: WooCommerce credentials were blanked, the webhook secret
 * was replaced with a fresh random one (breaking the signature check of every webhook WooCommerce
 * was already sending), hand-added variables (TRUSTED_PROXY_IPS ...) vanished, and nothing said so
 * and no copy was kept. Arms lift the SHIPPED functions and prompt lines into a `bash` and run them
 * over real files; each prints the precondition it reached.
 */
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import test from 'node:test'

import { shippedFunction } from './real-postgres-cluster.ts'
import { withTempDir } from './temp-dir.ts'

const REPO = process.cwd()
const INSTALL = readFileSync(join(REPO, 'scripts/install.sh'), 'utf8')

function bash(program: string): { status: number; out: string } {
  const r = spawnSync('bash', ['-c', program], {
    encoding: 'utf8',
    env: { PATH: process.env.PATH ?? '/usr/bin:/bin', LC_ALL: 'C' } as unknown as NodeJS.ProcessEnv,
  })
  return { status: r.status ?? -1, out: `${r.stdout ?? ''}${r.stderr ?? ''}` }
}

/** The previous run's file: one installer-owned key, secrets, and the hand-added keys the finding lost. */
const OLD_ENV = [
  '# generated by install.sh',
  'APP_PORT=3000',
  'AUTH_SECRET=old-auth',
  'WC_STORE_URL=https://shop.example.test',
  'WC_CONSUMER_KEY=ck_old',
  'WC_CONSUMER_SECRET=cs_old',
  'WC_WEBHOOK_SECRET=whsec_old',
  'TRUSTED_PROXY_IPS=10.0.0.1,10.0.0.2',
  'REQUIRE_TRUSTED_PROXY_CONFIG=true',
  'XERO_ALLOWED_TENANT_IDS=tenant-a=b#c',
  'FILE_SCAN_MODE=clamav',
  '',
].join('\n')

const LIB = [
  'set -uo pipefail',
  'exec 2>&1',
  'info() { echo "INFO: $*"; }; warn() { echo "WARN: $*"; }; error() { echo "ERROR: $*"; }',
  'die() { echo "DIE: $*"; exit 9; }',
  'APP_DIR=/opt/app; APP_USER=app; DB_ADMIN_CREDENTIAL_FILE=/etc/ims-db-admin/deploy-admin.env',
  'declare -A EXISTING_ENV=()',
  'declare -a EXISTING_ENV_RAW=() EXISTING_ENV_UNCLASSIFIED=()',
  'ENV_FILE_STATE=absent',
  'ENV_BACKUP_FILE=""; ENV_KEPT_KEYS=(); ENV_PRESERVED_BLOCK=""',
  shippedFunction(INSTALL, 'existing_env'),
  shippedFunction(INSTALL, 'load_existing_env'),
  shippedFunction(INSTALL, 'env_key_is_admin_credential'),
  shippedFunction(INSTALL, 'render_preserved_env_keys'),
  shippedFunction(INSTALL, 'write_env_backup'),
  shippedFunction(INSTALL, 'print_env_rewrite_summary'),
].join('\n')

/** The template output of a re-run, reduced to the keys the arms care about. */
const RENDERED = ['APP_PORT=3000', 'AUTH_SECRET=old-auth', 'WC_STORE_URL=https://shop.example.test', 'FILE_SCAN_MODE=clamav', 'NEW_KEY=1'].join('\n')

test('re-run: keys the installer does not own are carried over verbatim; owned ones are not duplicated', async () => {
  await withTempDir('ims-env-keep-', async (dir) => {
    const old = join(dir, '.env')
    writeFileSync(old, OLD_ENV)
    const r = bash([LIB, `load_existing_env '${old}'`, `rendered='${RENDERED}'`,
      'render_preserved_env_keys "${rendered}"; echo "RC=$?"', 'printf "%s" "${ENV_PRESERVED_BLOCK}"', 'echo "KEPT=${ENV_KEPT_KEYS[*]}"'].join('\n'))
    console.log(`  precondition: previous file read; kept -> ${JSON.stringify(r.out.split('\n').filter((l) => /^(KEPT|RC)=/.test(l)))}`)
    assert.match(r.out, /RC=0/)
    assert.match(r.out, /KEPT=REQUIRE_TRUSTED_PROXY_CONFIG TRUSTED_PROXY_IPS WC_CONSUMER_KEY WC_CONSUMER_SECRET WC_WEBHOOK_SECRET XERO_ALLOWED_TENANT_IDS/)
    assert.match(r.out, /^TRUSTED_PROXY_IPS=10\.0\.0\.1,10\.0\.0\.2$/m)
    assert.match(r.out, /^XERO_ALLOWED_TENANT_IDS=tenant-a=b#c$/m, 'a value containing = and # is carried byte for byte')
    assert.doesNotMatch(r.out, /^APP_PORT=/m, 'a key the template sets is not written twice')
    assert.doesNotMatch(r.out, /^FILE_SCAN_MODE=/m)
  })
})

test('re-run: a deploy admin credential left in the application .env is REFUSED, never carried forward', async () => {
  await withTempDir('ims-env-admin-', async (dir) => {
    const old = join(dir, '.env')
    writeFileSync(old, `${OLD_ENV}DEPLOY_ADMIN_DATABASE_URL=postgres://admin:SECRETPW@h/db\n`)
    const r = bash([LIB, `load_existing_env '${old}'`, `rendered='${RENDERED}'`,
      'render_preserved_env_keys "${rendered}"; echo "RC=$?"', 'printf "BLOCK=[%s]" "${ENV_PRESERVED_BLOCK}"'].join('\n'))
    console.log(`  admin key present -> ${JSON.stringify(r.out.split('\n').filter((l) => /RC=|ERROR/.test(l)).map((l) => l.slice(0, 90)))}`)
    assert.match(r.out, /RC=1/)
    assert.match(r.out, /ERROR: .*DEPLOY_ADMIN_DATABASE_URL.*must never hold the deploy admin credential/)
    assert.doesNotMatch(r.out, /SECRETPW/, 'and the value is never printed')
    assert.match(r.out, /BLOCK=\[\]/, 'no block was produced')
  })
})

test('re-run: a timestamped mode-600 backup of the old file is written from what was read, before anything is replaced', async () => {
  await withTempDir('ims-env-bak-', async (dir) => {
    const old = join(dir, '.env')
    writeFileSync(old, OLD_ENV)
    const target = join(dir, 'captured')
    const r = bash([LIB, 'date() { echo 20261008T120000Z; }',
      // publish_durable_file replaced by a recorder: arguments + stdin.
      `publish_durable_file() { echo "PUBLISH $1 $2 $3" > '${target}.args'; cat > '${target}.body'; }`,
      `load_existing_env '${old}'`, 'APP_DIR=/opt/app', 'write_env_backup; echo "RC=$?"', 'echo "FILE=${ENV_BACKUP_FILE}"'].join('\n'))
    const args = readFileSync(`${target}.args`, 'utf8').trim()
    console.log(`  backup: ${args}`)
    assert.match(r.out, /RC=0/)
    assert.equal(args, 'PUBLISH /opt/app/.env.bak-20261008T120000Z app:app 600')
    assert.equal(readFileSync(`${target}.body`, 'utf8'), OLD_ENV, 'the backup is the old file byte for byte')
    // First install: nothing to back up, nothing published.
    const first = bash([LIB, 'publish_durable_file() { echo CALLED; }', 'write_env_backup; echo "RC=$? FILE=[${ENV_BACKUP_FILE}]"'].join('\n'))
    assert.match(first.out, /RC=0 FILE=\[\]/)
    assert.doesNotMatch(first.out, /CALLED/)
    assert.deepEqual(readdirSync(dir).filter((f) => f.startsWith('.env.bak')), [], 'precondition: the rig itself wrote no real backup')
    void statSync
  })
})

test('re-run: the summary names what was kept, changed and added, and never prints a value', async () => {
  await withTempDir('ims-env-sum-', async (dir) => {
    const old = join(dir, '.env')
    writeFileSync(old, OLD_ENV)
    const now = RENDERED.replace('APP_PORT=3000', 'APP_PORT=3001')
    const r = bash([LIB, `load_existing_env '${old}'`, 'ENV_BACKUP_FILE=/opt/app/.env.bak-x', `rendered='${now}'`,
      'render_preserved_env_keys "${rendered}" > /dev/null', 'print_env_rewrite_summary "${rendered}"'].join('\n'))
    console.log(`  summary: ${JSON.stringify(r.out.split('\n').map((l) => l.slice(0, 110)))}`)
    assert.match(r.out, /Backup \(mode 600\): \/opt\/app\/\.env\.bak-x/)
    assert.match(r.out, /kept as it was.*TRUSTED_PROXY_IPS/)
    assert.match(r.out, /values this run changed \(1\): APP_PORT/)
    assert.match(r.out, /keys this run added \(1\): NEW_KEY/)
    for (const secret of ['whsec_old', 'cs_old', 'ck_old', 'old-auth', '10.0.0.1']) assert.doesNotMatch(r.out, new RegExp(secret), `${secret} must not be printed`)
  })
})

test('re-run: lines that are not plain KEY=VALUE are counted and pointed at the backup, not silently dropped', async () => {
  await withTempDir('ims-env-uncl-', async (dir) => {
    const old = join(dir, '.env')
    writeFileSync(old, 'A=1\nexport B=2\nC = 3\n# comment\n\nD=4\n')
    const r = bash([LIB, `load_existing_env '${old}'`, 'ENV_BACKUP_FILE=/b', 'print_env_rewrite_summary "A=1"'].join('\n'))
    console.log(`  unclassified: ${JSON.stringify(r.out.split('\n').filter((l) => /WARN/.test(l)).map((l) => l.slice(0, 120)))}`)
    assert.match(r.out, /WARN:   2 line\(s\) .*line numbers: 2 3\) and were NOT carried over; they are in the backup/)
  })
})

/** A block of shipped lines from `first` through `last` inclusive. */
function shippedBlock(first: RegExp, last: RegExp): string {
  const lines = INSTALL.split('\n')
  const start = lines.findIndex((l) => first.test(l))
  const end = lines.findIndex((l, i) => i >= start && last.test(l))
  assert.ok(start > 0 && end >= start, `precondition: block ${first} .. ${last} found (${start}..${end})`)
  return lines.slice(start, end + 1).join('\n')
}

const WC_BLOCK = shippedBlock(/^prompt WC_STORE_URL /, /^unset _wc_name$/)

const wcProgram = (existing: string, exports: string): string =>
  ['set -uo pipefail', 'NON_INTERACTIVE=true', 'declare -A EXISTING_ENV=()', existing,
    shippedFunction(INSTALL, 'existing_env'), shippedFunction(INSTALL, 'prompt'), exports, WC_BLOCK,
    'echo "URL=[${WC_STORE_URL}] KEY=[${WC_CONSUMER_KEY}] SECRET=[${WC_CONSUMER_SECRET}] HOOK=[${WC_WEBHOOK_SECRET}]"'].join('\n')

const WC_EXISTING = 'EXISTING_ENV[WC_STORE_URL]=https://shop.example.test; EXISTING_ENV[WC_CONSUMER_KEY]=ck_old; EXISTING_ENV[WC_CONSUMER_SECRET]=cs_old; EXISTING_ENV[WC_WEBHOOK_SECRET]=whsec_old'

test('re-run: WooCommerce credentials and the webhook secret default to the installed ones; only "none" clears', () => {
  const kept = bash(wcProgram(WC_EXISTING, ''))
  const fresh = bash(wcProgram('', ''))
  const cleared = bash(wcProgram(WC_EXISTING, 'export WC_STORE_URL=none WC_CONSUMER_KEY=none WC_CONSUMER_SECRET=none WC_WEBHOOK_SECRET=none'))
  const blank = bash(wcProgram(WC_EXISTING, 'export WC_STORE_URL= WC_WEBHOOK_SECRET='))
  const override = bash(wcProgram(WC_EXISTING, 'export WC_WEBHOOK_SECRET=whsec_new'))
  console.log(`  WC re-run default -> ${kept.out.trim()}`)
  console.log(`  WC first install  -> ${fresh.out.trim().replace(/HOOK=\[[0-9a-f]+\]/, 'HOOK=[<random>]')}`)
  console.log(`  WC none -> ${cleared.out.trim()}; blank export -> ${blank.out.trim()}; override -> ${override.out.trim()}`)
  assert.match(kept.out, /URL=\[https:\/\/shop\.example\.test\] KEY=\[ck_old\] SECRET=\[cs_old\] HOOK=\[whsec_old\]/)
  assert.match(fresh.out, /URL=\[\] KEY=\[\] SECRET=\[\] HOOK=\[[0-9a-f]{32}\]/, 'a first install still mints a webhook secret')
  assert.match(cleared.out, /URL=\[\] KEY=\[\] SECRET=\[\] HOOK=\[\]/)
  assert.match(blank.out, /URL=\[https:\/\/shop\.example\.test\].*HOOK=\[whsec_old\]/, 'a blank is not a request to clear')
  assert.match(override.out, /HOOK=\[whsec_new\]/)
})

test('re-run: the domain, port and upload-scanner settings default to what is installed', () => {
  const dom = shippedBlock(/^EXISTING_APP_DOMAIN=/, /^prompt APP_PORT /)
  const ask = (existing: string) => bash(['set -uo pipefail', 'NON_INTERACTIVE=true', 'declare -A EXISTING_ENV=()', existing,
    shippedFunction(INSTALL, 'existing_env'), shippedFunction(INSTALL, 'prompt'), dom, 'echo "DOMAIN=[${APP_DOMAIN}] PORT=[${APP_PORT}]"'].join('\n'))
  const installed = ask('EXISTING_ENV[NEXT_PUBLIC_APP_URL]=https://ims.example.test; EXISTING_ENV[APP_PORT]=3055')
  const firstRun = ask('')
  console.log(`  domain/port: installed -> ${installed.out.trim()}; first install -> ${firstRun.out.trim()}`)
  assert.match(installed.out, /DOMAIN=\[ims\.example\.test\] PORT=\[3055\]/)
  assert.match(firstRun.out, /DOMAIN=\[ims\.localhost\] PORT=\[3000\]/)

  const scan = shippedBlock(/^FILE_SCAN_MODE="\$\(existing_env /, /^FILE_SCAN_TIMEOUT_MS="/)
  const scanAsk = (existing: string) => bash(['set -uo pipefail', 'declare -A EXISTING_ENV=()', existing, shippedFunction(INSTALL, 'existing_env'), scan,
    'echo "MODE=[${FILE_SCAN_MODE}] CMD=[${FILE_SCAN_COMMAND}] TIMEOUT=[${FILE_SCAN_TIMEOUT_MS}]"'].join('\n'))
  const tuned = scanAsk('EXISTING_ENV[FILE_SCAN_MODE]=clamav; EXISTING_ENV[FILE_SCAN_COMMAND]=/usr/bin/clamdscan; EXISTING_ENV[FILE_SCAN_TIMEOUT_MS]=90000')
  const factory = scanAsk('')
  console.log(`  scanner: tuned -> ${tuned.out.trim()}; first install -> ${factory.out.trim()}`)
  assert.match(tuned.out, /MODE=\[clamav\] CMD=\[\/usr\/bin\/clamdscan\] TIMEOUT=\[90000\]/)
  assert.match(factory.out, /MODE=\[disabled\] CMD=\[\] TIMEOUT=\[30000\]/)
})

test('re-run: the .env write backs up and keeps before it replaces, and the source sync does not delete backups', () => {
  const body = shippedFunction(INSTALL, 'write_app_env_file')
  const order = ['render_app_env_file', 'render_preserved_env_keys', 'write_env_backup', 'publish_durable_file'].map((n) => body.indexOf(n))
  console.log(`  write_app_env_file call order offsets: ${order.join(' < ')}`)
  assert.ok(order.every((o) => o > 0) && order.every((o, i) => i === 0 || o > order[i - 1]), 'render, preserve, back up, then publish')
  const excludes = INSTALL.split('\n').filter((l) => l.trim() === "--exclude='.env.bak*' \\")
  console.log(`  rsync .env.bak* excludes: ${excludes.length}`)
  assert.equal(excludes.length, 2, 'both rsync --delete calls spare the backups')
  assert.match(INSTALL, /^print_env_rewrite_summary "\$\{ENV_LAST_RENDERED\}"$/m, 'and the summary is printed after the write')
})
