/**
 * o3d-zjsb5.9 round 10: THE OPERATOR RECOVERY PATH for the duplicate-recipe refusal.
 *
 * Round 8 made `syncBomRecipeFromProductComponents` REFUSE while another ACTIVE `Bom` holds
 * `BomItem` rows for the same parent, because `replenishment-reports.ts` reads every active
 * `BomItem` whose parent is BOM-typed and has no "the claimed Bom wins" rule — two active recipes
 * for one product means planning ADDS both and over-orders. Refusing beats silently double-counting.
 *
 * But that refusal blocked the product's import, its component edit AND its build orders, and told
 * the operator to "deactivate the duplicate BOM" — which NOTHING in the application could do. There
 * is no Bom list, no Bom detail page, and no server action anywhere writes `bom.update`. The only
 * way out was hand-editing production data, and the worst place to meet that is the first load,
 * inside the quiescent switchover window, with the catalogue import blocked.
 *
 * WHY A COMMAND AND NOT A BUTTON. An authorized action would have to invent the surface to put it
 * on: a Bom has no page, so it would mean a new route, a new client component, permission wiring and
 * a route-auth policy entry, for something a first load needs ONCE per stray legacy row. The
 * switchover needs an executable path, not necessarily a button. This is that path, and the reader-
 * side fix that makes duplicates harmless rather than merely detectable stays in o3d-zjsb5.30.
 *
 * WHAT IT REFUSES, because "deactivate this row" is not always safe:
 *   · a Bom CLAIMED by a product (`productId` set) is that product's live recipe — deactivating it
 *     would make a BOM-typed product silently unplannable, which is the o3d-zjsb5.29 defect;
 *   · a Bom that is the LAST active recipe of some OTHER BOM-typed parent would do the same to that
 *     product. One Bom row can legitimately hold items for several parents, so this must be checked
 *     per parent rather than assumed.
 * In both cases nothing is written and the caller is told which product is in the way.
 *
 * IT NEVER DELETES. The items are kept, deactivated, exactly as a type conversion retires a recipe:
 * `manufacturing-analytics.ts` values a completed production order through `order.bom.items`, so
 * deleting them would rewrite history to prettify a check (o3d-zjsb5.29/.30).
 */
import type { Prisma } from '@/app/generated/prisma/client'

import { COMPONENT_GRAPH_WRITE_LOCK_KEY } from '@/lib/db/advisory-locks'
import { withSavepoint } from '@/lib/db/savepoint'
import { PLANNING_REACHABLE_BOM_EDGES } from '@/lib/products/bom-recipe'

/**
 * A transaction client with exactly the models this needs. Prisma's own type, not a hand-rolled
 * structural one: a hand-rolled `(args: unknown) => Promise<unknown>` is NOT assignable from Prisma's
 * typed methods (the argument types are contravariant), so it forces an `as never` at the call site
 * and throws away the type checking that would catch a wrong `where`.
 */
type RepairClient = Pick<
  Prisma.TransactionClient,
  '$executeRaw' | '$queryRaw' | 'bom' | 'bomItem' | 'activityLog'
>

/**
 * WHICH SERVER THIS IS, as far as Postgres can actually tell us (round 13).
 *
 * Round 12 asserted `current_database()`, and round 13 turned round 12's own argument back on it: a
 * RESTORED COPY KEEPS ITS NAME. So a clone on a different server satisfied both the pre-flight check and
 * the in-transaction re-check. The guard proved "this database is called X"; what an operator needs is
 * "this is the server I meant" — sound, and establishing the wrong thing.
 *
 * So the identity is a COMPOSITE of everything that genuinely varies between servers here:
 *   · `current_database()`   — the name. Cheap, human-meaningful, and NOT distinguishing on its own.
 *   · `inet_server_addr()` / `inet_server_port()` — where this connection actually landed. NULL over a
 *     unix socket, which is itself worth seeing, since the socket form is how a URL loses its `?host=`.
 *   · `pg_control_system().system_identifier` — the cluster's own id, generated by initdb.
 *
 * WHAT A CLONE CAN STILL DEFEAT, stated because a guard whose limit is written down is worth more than
 * one that implies it is total:
 *   · A PHYSICAL clone — `pg_basebackup`, a streaming replica, a snapshot restore — COPIES the
 *     `system_identifier`. Same name, same identifier: only host/port distinguish it, and if it is
 *     reached on the same address and port through a proxy, NOTHING here distinguishes it. This guard
 *     cannot close that, and does not claim to.
 *   · A LOGICAL restore — `pg_dump` into a fresh `initdb` — gets a NEW `system_identifier`, so it IS
 *     distinguished. That is the common "someone restored a copy of production" case.
 *   · `pg_control_system()` is READABLE BY AN ORDINARY ROLE on PostgreSQL 17 — verified, not assumed: a
 *     plain `CREATE ROLE ... LOGIN` with no grants reads `system_identifier`, `pg_control_checkpoint()`
 *     and `pg_is_in_recovery()`. So the identifier is normally AVAILABLE and this composite is normally
 *     at full strength. (An earlier version of this comment claimed the opposite, which would have led a
 *     future author to design around a constraint that does not exist.)
 *     The `unavailable` path below is therefore DEFENSIVE and the exception, not the expected case:
 *     `EXECUTE` can be revoked, and a managed provider may restrict these functions. Where it happens
 *     the field reads `unavailable`, the composite degrades to name + address, and the banner says so
 *     rather than silently comparing fewer things.
 */
export type ServerIdentity = {
  database: string
  host: string
  port: string
  systemIdentifier: string
}

export type ServerIdentityDifference = { field: keyof ServerIdentity; expected: string; actual: string }

/**
 * Reads the composite from the SERVER, never from the connection URL — the URL is the part that lies.
 *
 * `includeSystemIdentifier: false` skips the optional query entirely. Callers that already know the role
 * cannot read it pass that, so inside a mutation transaction the query never runs at all — which is the
 * safest answer to the problem below.
 *
 * THE OPTIONAL QUERY IS WRAPPED IN A SAVEPOINT (round 16, HIGH 3), and catching the JavaScript error is
 * NOT sufficient on its own. PostgreSQL aborts the WHOLE transaction on any error, including a permission
 * denial, so a bare try/catch leaves the transaction in state 25P02 and every later statement fails with
 * "current transaction is aborted" — the BOM queries below would die, reach the generic handler, and a
 * role denied EXECUTE could not use this command as documented at all. This repository already knows the
 * family: see lib/db/savepoint.ts, written because a caught P2002 left the same wreckage. Rolling back to
 * a savepoint is what actually clears the aborted state.
 */
export async function readServerIdentity(
  client: Pick<Prisma.TransactionClient, '$queryRaw'>,
  options: { includeSystemIdentifier?: boolean } = {},
): Promise<ServerIdentity> {
  const rows = await client.$queryRaw<Array<{
    database: string; host: string | null; port: string | null
  }>>`
    SELECT current_database()::text AS database,
           inet_server_addr()::text AS host,
           inet_server_port()::text AS port
  `
  const row = rows[0]

  let systemIdentifier = 'unavailable'
  if (options.includeSystemIdentifier !== false) {
    try {
      const control = await withSavepoint(client, async () => await client.$queryRaw<Array<{ id: string }>>`
        SELECT system_identifier::text AS id FROM pg_control_system()
      `)
      systemIdentifier = control[0]?.id ?? 'unavailable'
    } catch {
      // The savepoint above has already rolled the failure back, so the transaction is usable.
      systemIdentifier = 'unavailable'
    }
  }
  return {
    database: row?.database ?? 'unknown',
    host: row?.host ?? 'local socket',
    port: row?.port ?? 'local socket',
    systemIdentifier,
  }
}

/**
 * Is `system_identifier` readable on this connection? Answered OUTSIDE any mutation transaction so the
 * optional query never has to run inside one (round 16, HIGH 3, preferred shape).
 */
export async function systemIdentifierIsReadable(
  client: Pick<Prisma.TransactionClient, '$queryRaw'>,
): Promise<boolean> {
  return (await readServerIdentity(client)).systemIdentifier !== 'unavailable'
}

/**
 * THE ONE DECISION about whether a write has established its target — pure, total, and the only thing the
 * command consults (round 20).
 *
 * WHY THIS IS A FUNCTION RATHER THAN A PREDICATE INLINE IN THE SCRIPT. Rounds 16 and 18 each closed one
 * existential gap in that predicate -- "is `--expect-db` the sole pin?", then "are all the pins
 * clone-invariant?" -- and each time the NEXT combination was left for the next reader to find. Patching
 * sibling conditions one at a time does not terminate, because an assertion about the combinations someone
 * thought of proves nothing about the ones they did not.
 *
 * Extracting the decision makes the input space ENUMERABLE: four pinnable fields and one acknowledgement
 * flag, so 32 total inputs, all of which a generated test asserts over. That is a universal statement about
 * every reachable combination, including combinations nobody has imagined, which is what no amount of
 * further predicate patching could give.
 *
 * THE RULE, and it is the whole rule:
 *   · the target database must be NAMED -- nothing else says WHICH database is meant; and
 *   · identity must be established by the CLUSTER IDENTIFIER, or the weaker mode explicitly ACKNOWLEDGED.
 * Host and port are checked when supplied but discharge nothing, because they are clone-invariant: see
 * {@link ServerIdentity}. A restored copy matches on name, host and port together, so no number of them
 * distinguishes it.
 */
export type IdentityDischarge =
  | { allowed: true; route: 'system-identifier' | 'name-only-acknowledged' }
  | { allowed: false; reason: 'unnamed-database' | 'not-established' }

export function dischargeIdentity(input: {
  pinnedFields: ReadonlyArray<keyof ServerIdentity>
  acknowledged: boolean
}): IdentityDischarge {
  if (!input.pinnedFields.includes('database')) return { allowed: false, reason: 'unnamed-database' }
  if (input.pinnedFields.includes('systemIdentifier')) return { allowed: true, route: 'system-identifier' }
  if (input.acknowledged) return { allowed: true, route: 'name-only-acknowledged' }
  return { allowed: false, reason: 'not-established' }
}

/**
 * PINS THAT CANNOT BE VERIFIED — a SEPARATE rule from {@link compareServerIdentity}, deliberately
 * (round 16, HIGH 2).
 *
 * `compareServerIdentity` SKIPS `systemIdentifier` when either side reads `unavailable`, and that is right
 * for the UNPINNED path: there the expected value is just what the preflight happened to observe, so
 * absence of evidence is not evidence of a mismatch.
 *
 * It is WRONG for a field the operator explicitly pinned. Letting one rule serve both meant an explicit
 * `--expect-system-id` was ACCEPTED AND THEN SILENTLY NOT CHECKED — and an operator who pins the
 * strongest field and is told nothing when it goes unverified is worse off than one who never pinned it,
 * because they believe they hold a guarantee they do not. Conflating the two cases was the defect.
 *
 * Returns the pinned fields that cannot be verified on this pair of reads. Non-empty means REFUSE.
 */
export function unverifiablePins(
  pinned: ReadonlyArray<keyof ServerIdentity>,
  expected: ServerIdentity,
  actual: ServerIdentity,
): Array<keyof ServerIdentity> {
  return pinned.filter((field) =>
    expected[field] === 'unavailable' || actual[field] === 'unavailable')
}

/** Every field that differs. Empty means the composite matches. */
export function compareServerIdentity(
  expected: ServerIdentity,
  actual: ServerIdentity,
): ServerIdentityDifference[] {
  const fields: Array<keyof ServerIdentity> = ['database', 'host', 'port', 'systemIdentifier']
  const differences: ServerIdentityDifference[] = []
  for (const field of fields) {
    // An `unavailable` identifier on EITHER side is not evidence of a mismatch — it is absence of
    // evidence, and treating it as a mismatch would make the command unusable for exactly the
    // non-superuser role it is most likely to run as.
    if (field === 'systemIdentifier'
      && (expected[field] === 'unavailable' || actual[field] === 'unavailable')) continue
    if (expected[field] !== actual[field]) {
      differences.push({ field, expected: expected[field], actual: actual[field] })
    }
  }
  return differences
}

/** One line an operator can read and act on. */
export function describeServerIdentity(identity: ServerIdentity): string {
  return `database=${identity.database} host=${identity.host} port=${identity.port} `
    + `system_identifier=${identity.systemIdentifier}`
}

export type BomRecipeRepairOutcome =
  /** Deactivated. `items` were KEPT — that is the point. */
  | { kind: 'deactivated'; bomId: string; itemCount: number; parentProductIds: string[] }
  /** Nothing to do; safe to run twice. */
  | { kind: 'already-inactive'; bomId: string }
  | { kind: 'not-found'; bomId: string }
  /** It is a product's live recipe. Refused. */
  | { kind: 'claimed'; bomId: string; productId: string; sku: string }
  /** Deactivating it would leave another BOM-typed product with no planning-visible recipe. Refused. */
  | { kind: 'sole-recipe-for-other-parent'; bomId: string; blockedBy: Array<{ productId: string; sku: string }> }
  /**
   * The connection is not to the SERVER the caller confirmed. Refused inside the transaction, so the
   * abort discards anything already written (round 12; widened to the composite in round 13).
   */
  /**
   * A field the operator explicitly PINNED could not be verified on either read (round 16, HIGH 2).
   * Distinct from `wrong-database`: nothing disagreed — the check could not be made at all, and saying
   * "matched" would be a lie about a guarantee the operator asked for.
   */
  | { kind: 'identity-unverifiable'; fields: Array<keyof ServerIdentity>; observed: ServerIdentity }
  | {
    kind: 'wrong-database'
    expected: ServerIdentity
    actual: ServerIdentity
    differences: ServerIdentityDifference[]
  }

/**
 * Deactivate one `Bom` by id, keeping its items, refusing when another product depends on it.
 *
 * MUST be called inside a transaction: it takes `COMPONENT_GRAPH_WRITE_LOCK_KEY` so the "is this the
 * last active recipe for that parent" question cannot be answered against a graph that changes
 * underneath it — the same reason every other writer of this graph takes it, and the same lesson as
 * rounds 4 and 8 (a check outside the lock describes a state the lock is not protecting).
 */
export async function deactivateDuplicateBomRecipe(
  client: RepairClient,
  args: {
    bomId: string
    actor?: string
    database?: string
    expectIdentity?: ServerIdentity
    /** Fields the operator explicitly pinned. These are STRICT: unverifiable means refuse. */
    pinnedFields?: ReadonlyArray<keyof ServerIdentity>
    /** False when the caller already established the role cannot read it — then it is never queried. */
    systemIdentifierReadable?: boolean
    /** True when the operator explicitly accepted the weaker name-only mode. Recorded in the audit row. */
    acceptedNameOnly?: boolean
    /**
     * WHICH ROUTE established the target: the cluster identifier, an explicit acknowledgement of the
     * weaker mode, or a name typed at a TTY. Recorded so the audit row states what was ESTABLISHED rather
     * than which flags appeared — `acceptedNameOnly: false` must never mean "no acknowledgement was
     * needed" when in fact nothing independently identified the server (round 18).
     */
    identityRoute?: string | null
  },
): Promise<BomRecipeRepairOutcome> {
  const { bomId } = args
  await client.$executeRaw`SELECT pg_advisory_xact_lock(${COMPONENT_GRAPH_WRITE_LOCK_KEY})`

  // WHICH SERVER IS THIS, ASKED AGAIN, IN HERE (round 12; the composite since round 13).
  //
  // The caller confirms the target before opening this transaction, and that check is necessary but not
  // sufficient: it ran on a different statement, and anything that changes which server the connection
  // reaches between then and now defeats it. That is not hypothetical here — a socket-form
  // `DATABASE_URL` losing its `?host=` silently retargets the shared cluster. Asking the server itself,
  // inside the transaction that does the writing, is what turns a banner into a guard: a mismatch here
  // aborts, and the abort discards the write.
  //
  // The COMPOSITE, not the name, for the reason in {@link ServerIdentity}: a restored copy keeps its
  // name, so comparing names proves only that this database is called what the operator expected.
  if (args.expectIdentity !== undefined) {
    const actual = await readServerIdentity(client, {
      // Not queried at all when the caller established outside this transaction that it is unreadable.
      includeSystemIdentifier: args.systemIdentifierReadable !== false,
    })

    // PINNED FIELDS FIRST, and strictly. A pin that cannot be verified is refused, not skipped -- the
    // separate rule in `unverifiablePins`, for the reason documented there. This also closes the second
    // half of HIGH 2: the stored expectation can hold `unavailable` from the preflight while the
    // transaction connection CAN read the identifier, and the lenient rule skipped that too.
    const unverifiable = unverifiablePins(args.pinnedFields ?? [], args.expectIdentity, actual)
    if (unverifiable.length > 0) {
      return { kind: 'identity-unverifiable', fields: unverifiable, observed: actual }
    }

    const differences = compareServerIdentity(args.expectIdentity, actual)
    if (differences.length > 0) {
      return { kind: 'wrong-database', expected: args.expectIdentity, actual, differences }
    }
  }

  const bom = await client.bom.findUnique({
    where: { id: bomId },
    select: { id: true, active: true, productId: true, product: { select: { sku: true } } },
  })
  if (!bom) return { kind: 'not-found', bomId }
  if (bom.productId) {
    return { kind: 'claimed', bomId, productId: bom.productId, sku: bom.product?.sku ?? bom.productId }
  }
  if (!bom.active) return { kind: 'already-inactive', bomId }

  // Every parent this row carries items for. A Bom is not necessarily one product's recipe.
  const items = await client.bomItem.findMany({
    where: { bomId },
    select: { parentProductId: true, parentProduct: { select: { sku: true, type: true } } },
  })

  // For each BOM-typed parent, is this the ONLY active Bom carrying its recipe? If so, deactivating
  // here would take that product out of planning entirely — the same silent unplannability the
  // refusal exists to prevent, just moved to a different product.
  const blockedBy: Array<{ productId: string; sku: string }> = []
  const parents = new Map<string, { sku: string; type: string }>()
  for (const item of items) {
    if (item.parentProduct) parents.set(item.parentProductId, item.parentProduct)
  }
  for (const [parentProductId, parent] of parents) {
    if (parent.type !== 'BOM') continue
    const otherActive = await client.bomItem.findMany({
      where: {
        parentProductId,
        bomId: { not: bomId },
        ...PLANNING_REACHABLE_BOM_EDGES,
      },
      select: { bomId: true },
      take: 1,
    })
    if (otherActive.length === 0) {
      blockedBy.push({ productId: parentProductId, sku: parent.sku })
    }
  }
  if (blockedBy.length > 0) return { kind: 'sole-recipe-for-other-parent', bomId, blockedBy }

  await client.bom.update({ where: { id: bomId }, data: { active: false } })

  // LOGGED, because this is a deliberate change to production data made outside the UI. `userId` is
  // nullable precisely so a command can record itself.
  await client.activityLog.create({
    data: {
      entityType: 'PRODUCT',
      entityId: [...parents.keys()][0] ?? null,
      action: 'updated',
      tag: 'manufacturing',
      level: 'WARNING',
      description:
        `Deactivated duplicate manufacturing BOM ${bomId} (${items.length} recipe line(s) KEPT) via `
        + `scripts/deactivate-duplicate-bom.ts${args.actor ? ` by ${args.actor}` : ''}`
        + `${args.database ? ` on database ${args.database}` : ''}. It was not any product's claimed `
        + 'recipe and was not the last active recipe for any BOM-typed parent.',
      metadata: {
        bomId,
        itemCount: items.length,
        parentProductIds: [...parents.keys()],
        // WHICH DATABASE, recorded in the row itself. A repair run by hand during a load window is
        // exactly the case where "was that done on stage or on production?" gets asked afterwards.
        database: args.database ?? null,
        // THE WEAKER MODE IS VISIBLE AFTER THE FACT (round 16, HIGH 1). A name-only confirmation cannot
        // tell a same-name copy from the real server, so a run that accepted that has to be
        // distinguishable later from one that pinned the cluster identity.
        acceptedNameOnly: args.acceptedNameOnly === true,
        identityRoute: args.identityRoute ?? null,
        pinnedFields: [...(args.pinnedFields ?? [])],
        reason: 'o3d-zjsb5.9 duplicate-recipe repair',
      },
    },
  })

  return { kind: 'deactivated', bomId, itemCount: items.length, parentProductIds: [...parents.keys()] }
}

/** The operator-facing line for each outcome, shared by the script and its tests. */
export function describeBomRecipeRepair(outcome: BomRecipeRepairOutcome): string {
  switch (outcome.kind) {
    case 'deactivated':
      return `Deactivated BOM ${outcome.bomId}. Its ${outcome.itemCount} recipe line(s) were KEPT, so past `
        + 'build orders still report correctly. Re-run the import.'
    case 'already-inactive':
      return `BOM ${outcome.bomId} is already inactive — nothing to do.`
    case 'not-found':
      return `No BOM with id ${outcome.bomId}.`
    case 'claimed':
      return `REFUSED: BOM ${outcome.bomId} is the live recipe of ${outcome.sku}. Deactivating it would make `
        + 'that product unplannable. If you meant to retire that product\'s recipe, change its type instead.'
    case 'identity-unverifiable':
      return 'REFUSED: you pinned '
        + `${outcome.fields.join(', ')}, but that could not be VERIFIED on this connection `
        + `(it reads "unavailable"). Nothing was written.\n`
        + `  server reports: ${describeServerIdentity(outcome.observed)}\n`
        + '  This is refused rather than skipped on purpose: accepting a pin and then not checking it '
        + 'would leave you believing you had a guarantee you do not have. An ordinary role can normally '
        + 'read pg_control_system(), so EXECUTE has probably been revoked on this database — either grant '
        + 'it, or drop the pin and confirm the weaker mode explicitly.'
    case 'wrong-database':
      return 'REFUSED inside the transaction: this is not the server that was confirmed. Nothing was '
        + 'written.\n'
        + `  expected: ${describeServerIdentity(outcome.expected)}\n`
        + `  found:    ${describeServerIdentity(outcome.actual)}\n`
        + `  differs on: ${outcome.differences.map((d) => d.field).join(', ')}\n`
        + '  Check DATABASE_URL. A cloned database holds the same BOM ids AND the same name, so neither '
        + 'the id nor the name can tell two servers apart.'
    case 'sole-recipe-for-other-parent':
      return `REFUSED: BOM ${outcome.bomId} is the only active recipe for `
        + `${outcome.blockedBy.map((row) => row.sku).join(', ')}. Deactivating it would remove `
        + 'that product from planning. Give that product its own recipe first.'
  }
}
